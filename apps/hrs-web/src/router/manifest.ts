/** 菜单和路由缓存共用清单指纹；字段或结构变化后，旧缓存自动失效。 */
const source = JSON.stringify(MENU_MANIFEST);
let hash = 5381;
for (let index = 0; index < source.length; index += 1) {
  hash = ((hash << 5) + hash + source.charCodeAt(index)) | 0;
}
export const MENU_MANIFEST_FINGERPRINT = `${hash.toString(36)}-${source.length.toString(36)}`;
